#!/usr/bin/env python3
"""build-area-index.py — the subspecialty index: every area, its one hub, and the spokes under it.

Reads 03-skills/skills.registry.json (hubs declare `area:` in frontmatter; see
02-shared-references/skill-frontmatter.md) and writes 02-shared-references/skill-areas.md, so a
person or agent can find the skill that owns a subspecialty without loading a hub first.

Fails when two hubs claim the same area: one home per subspecialty
(design-skill-architecture, 2026-10-22).

Usage:
  python3 09-tools/build-area-index.py           # write
  python3 09-tools/build-area-index.py --check   # CI: fail on drift or a contested area
Stdlib only.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "03-skills" / "skills.registry.json"
OUT = ROOT / "02-shared-references" / "skill-areas.md"
SHOWN_TRIGGERS = 4


def render(skills: dict) -> tuple[str, list[str]]:
    errors: list[str] = []
    hubs: dict[str, str] = {}
    for name, rec in sorted(skills.items()):
        area = rec.get("area")
        if not area:
            continue
        if area in hubs:
            errors.append(f"area `{area}` is claimed by both `{hubs[area]}` and `{name}`")
            continue
        hubs[area] = name
    lines = [
        "# Skill areas — the subspecialty index",
        "",
        "_Generated by `09-tools/build-area-index.py` from each hub's `area:`. Do not edit by hand._",
        "",
        "Each area has one hub; each subspecialty has one spoke. Ask for the spoke by its triggers",
        "and the load chain brings the hub and its foundation first.",
        "",
    ]
    for area, hub in sorted(hubs.items()):
        rec = skills[hub]
        lines.append(f"## {area}")
        lines.append("")
        lines.append(f"Hub: `{hub}` ({rec.get('domain') or 'no domain'}) · `{rec['path']}`")
        lines.append("")
        spokes = sorted(n for n, r in skills.items() if r.get("hub") == hub and n != hub)
        lenses = sorted(n for n, r in skills.items() if hub in (r.get("governs") or []))
        if spokes:
            lines.append("| Spoke | Reached by |")
            lines.append("|---|---|")
            for s in spokes:
                trig = skills[s].get("triggers") or []
                shown = ", ".join(f"`{t}`" for t in trig[:SHOWN_TRIGGERS]) or "_no triggers: hub routes it_"
                if len(trig) > SHOWN_TRIGGERS:
                    shown += f" (+{len(trig) - SHOWN_TRIGGERS})"
                lines.append(f"| `{s}` | {shown} |")
            lines.append("")
        else:
            lines.append("_No spokes yet._")
            lines.append("")
        if lenses:
            lines.append("Lenses after output: " + ", ".join(f"`{l}`" for l in lenses))
            lines.append("")
    return "\n".join(lines).rstrip() + "\n", errors


def main(argv: list[str]) -> int:
    skills = json.loads(REGISTRY.read_text(encoding="utf-8"))["skills"]
    text, errors = render(skills)
    for e in errors:
        print(f"build-area-index: {e}", file=sys.stderr)
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("build-area-index: skill-areas.md is stale — run python3 09-tools/build-area-index.py",
                  file=sys.stderr)
            return 1
        return 1 if errors else 0
    OUT.write_text(text, encoding="utf-8")
    print(f"✓ wrote {OUT.relative_to(ROOT)} — {text.count(chr(10) + '## ')} areas")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
